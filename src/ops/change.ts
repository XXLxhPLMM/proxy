/**
 * @fileoverview 写操作的结果形状：ops 层唯一的「改成了什么」出口
 * @module ops/change
 * @description
 * 写面**返回**结果，不**回调**传输层的写入面。回调式（`io.changed(msg)`）会把「谁来显示这句话」
 * 反向焊进 ops，而那句话要不要打前缀、走 stdout 还是 stderr、要不要附一句「多久生效」，
 * **全是传输层的决定**——让它进来，本层就再也当不成一个能挂在 HTTP 面后面的东西。
 *
 * ⚠️ **`changed: false` 是一次成功，不是失败**：它表示这次调用的目标状态**本来就**是那样
 * （名单里已经有那条 / 本来就没有那条）。用户达到了目的，故它不报错；但数据一个字节都没动，
 * 故它也**不许**假装成功。如实返回 `false`，让传输层自己决定怎么呈现。把它当失败会让人以为
 * 操作坏了，把它当成功会掩盖「我以为改了、其实没改」——而那正是本仓最恨的一类假绿。
 *
 * `message` 是**中性事实陈述**（「已删除账号 alice」），不是命令语气、不是建议、也不带前缀。
 * 传输层可以把它原样打到任何一条通道上。
 *
 * ## 为什么单独一个文件
 *
 * 账号写面与名单写面共用这一个形状，故它不属于其中任何一个；放在 `./index.js` 则本目录内的
 * 兄弟模块就得自我引用 barrel（根 `AGENTS.md` 的 import 路径规约禁止）。
 *
 * @module
 */

/** 一次写操作的结果 */
export interface OpsChange {
  /** 数据是否真的变了（幂等 no-op 为 `false`） */
  readonly changed: boolean;
  /** 中性事实陈述，一句话 */
  readonly message: string;
}